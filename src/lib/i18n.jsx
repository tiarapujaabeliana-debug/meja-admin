const Ctx = createContext(null);

export function PenyediaBahasa({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem("meja-admin-bahasa") || "id"; } catch { return "id"; }
  });
  useEffect(() => {
    try { localStorage.setItem("meja-admin-bahasa", lang); } catch { /* mode privat */ }
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback((kunci, ganti) => {
    let s = KAMUS[lang]?.[kunci] ?? KAMUS.id[kunci] ?? kunci;
    if (ganti) for (const [k, v] of Object.entries(ganti)) s = s.split(k).join(v);
    return s;
  }, [lang]);

  /** Untuk nilai dwibahasa yang tersimpan di data ({id, en}). */
  const L = useCallback((o) => (o && typeof o === "object" && !Array.isArray(o))
    ? (o[lang] ?? o.id ?? "") : (o ?? ""), [lang]);

  return <Ctx.Provider value={{ lang, setLang, t, L }}>{children}</Ctx.Provider>;
}

export function useBahasa() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useBahasa dipakai di luar PenyediaBahasa");
  return v;
}